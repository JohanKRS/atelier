import { t } from './i18n.js';
// Pure geometry helpers for the frame of Expandir: coordinates are native image pixels, not screen pixels.
//
// The frame is the picture that will come out. It has a size (width × height) and says where the image sits in it:
// (x, y) is the image's top left corner in the frame's own coordinates. A negative x cuts the left of the image off;
// a positive one leaves room at the left, which is generated. So one frame crops the image, extends it, or both.
export const snap16 = n => Math.round(n / 16) * 16;
/** The least a frame keeps of the image, and the least a side of it measures, while it is being dragged. */
const KEEP = 32;

/** What a frame does to an image: nothing ('same'), 'crop' (it is inside the image), 'expand' (it holds the whole image) or 'both'. */
export function frameKind(width, height, x, y, iw, ih) {
  if (x <= 0 && y <= 0 && x + iw >= width && y + ih >= height) return width === iw && height === ih ? 'same' : 'crop';
  return x >= 0 && y >= 0 && x + iw <= width && y + ih <= height ? 'expand' : 'both';
}
/** The part of the image a frame keeps, in the image's own pixels. */
export function keptArea(width, height, x, y, iw, ih) {
  const left = Math.max(0, -x), top = Math.max(0, -y);
  return { x: left, y: top, width: Math.max(0, Math.min(iw, width - x) - left), height: Math.max(0, Math.min(ih, height - y) - top) };
}
/** The sizes the image APIs generate, and the ones a model on the account's GPU does (it brings its result to any size). */
export const API_LIMITS = { side: 3840, area: 8294400, ratio: 3, minArea: 655360, gpu: false };
export const GPU_LIMITS = { side: 12000, area: 40000000, ratio: 5, minArea: 4096, gpu: true };
/** Larger than the model generates. */
export const frameTooLarge = (width, height, limits = API_LIMITS) => Math.max(width, height) > limits.side || width * height > limits.area;
/**
 * Why a frame can't be used, or ''. A frame inside the image only crops, on the device, so any size will do. One that
 * reaches outside the image is generated by the model, which takes sizes in multiples of 16 within its limits.
 */
export function validateFrame(width, height, x, y, iw, ih, limits = API_LIMITS) {
  if (![width, height, x, y].every(Number.isInteger) || width < 16 || height < 16) return t('Use whole dimensions, from 16 px up.');
  const kept = keptArea(width, height, x, y, iw, ih);
  if (kept.width < 16 || kept.height < 16) return t('The frame must include part of the image.');
  const kind = frameKind(width, height, x, y, iw, ih);
  if (kind === 'same') return t('Drag the frame\'s handles: inward, the image is cropped; outward, the canvas grows.');
  if (kind === 'crop') return '';
  if (width % 16 || height % 16) return t('With a new area, use dimensions in multiples of 16.');
  if (limits.gpu) {
    if (frameTooLarge(width, height, limits) || Math.max(width, height) / Math.min(width, height) > limits.ratio) return t('With a new area, the canvas must stay within 12,000 px per side, 40 MP and an aspect ratio up to 5:1.');
    return '';
  }
  if (frameTooLarge(width, height) || Math.max(width, height) / Math.min(width, height) > 3) return t('With a new area, the canvas must stay within 3,840 px per side, 8.29 MP and an aspect ratio up to 3:1.');
  if (width * height < 655360) return t('With a new area, the canvas must be at least 0.66 MP (for example, 1024 × 640). Enlarge the frame or crop without leaving the image.');
  return '';
}

/** One side of the frame brought to a multiple of 16. The edge being dragged gives way; otherwise one that is not flush with the image. */
function settleSide(a, b, size, movedA, movedB) {
  const length = Math.max(16, snap16(b - a));
  if (length === b - a) return [a, b];
  return movedA || (!movedB && b === size && a !== 0) ? [b - length, b] : [a, a + length];
}
/** The frame with these edges (in the image's pixels). Once it reaches outside the image, its sides are multiples of 16. */
function settle(left, top, right, bottom, iw, ih, moved = {}) {
  if (left < 0 || top < 0 || right > iw || bottom > ih) {
    [left, right] = settleSide(left, right, iw, moved.w, moved.e);
    [top, bottom] = settleSide(top, bottom, ih, moved.n, moved.s);
  }
  return { width: right - left, height: bottom - top, x: 0 - left, y: 0 - top };
}
/**
 * The frame after one of its handles (n, s, e, w, or a corner such as nw) is dragged by (dx, dy) image pixels. An edge
 * that comes within `magnet` pixels of an edge of the image sticks to it, so a side can be left exactly as it is.
 */
export function resizeFrame(frame, handle, dx, dy, iw, ih, magnet = 0) {
  let left = -frame.x, top = -frame.y, right = left + frame.width, bottom = top + frame.height;
  const keepW = Math.min(KEEP, iw), keepH = Math.min(KEEP, ih);
  const stick = (v, size) => (Math.abs(v) <= magnet ? 0 : Math.abs(v - size) <= magnet ? size : Math.round(v));
  const moved = { w: handle.includes('w'), e: handle.includes('e'), n: handle.includes('n'), s: handle.includes('s') };
  if (moved.w) left = Math.min(stick(left + dx, iw), right - keepW, iw - keepW);
  if (moved.e) right = Math.max(stick(right + dx, iw), left + keepW, keepW);
  if (moved.n) top = Math.min(stick(top + dy, ih), bottom - keepH, ih - keepH);
  if (moved.s) bottom = Math.max(stick(bottom + dy, ih), top + keepH, keepH);
  return settle(left, top, right, bottom, iw, ih, moved);
}
/** The frame after the image is dragged by (dx, dy) inside it. An edge of the image that comes close to the same edge of the frame sticks to it. */
export function panFrame(frame, dx, dy, iw, ih, magnet = 0) {
  const stick = (v, room) => (Math.abs(v) <= magnet ? 0 : Math.abs(v - room) <= magnet ? room : Math.round(v));
  const x = Math.max(Math.min(KEEP, iw) - iw, Math.min(frame.width - Math.min(KEEP, iw), stick(frame.x + dx, frame.width - iw)));
  const y = Math.max(Math.min(KEEP, ih) - ih, Math.min(frame.height - Math.min(KEEP, ih), stick(frame.y + dy, frame.height - ih)));
  return settle(-x, -y, frame.width - x, frame.height - y, iw, ih);
}
/** The frame with a typed size: its top left corner stays where it is, and it keeps a part of the image. */
export function sizeFrame(frame, width, height, iw, ih) {
  return { width, height, x: Math.max(16 - iw, Math.min(width - 16, frame.x)), y: Math.max(16 - ih, Math.min(height - 16, frame.y)) };
}
// Recortar: the same frame, kept inside the image. It only cuts, so its sides take any whole size.
/** The crop frame after one of its handles is dragged: its edges stay inside the image, at least 32 px apart. */
export function resizeCrop(frame, handle, dx, dy, iw, ih, magnet = 0) {
  let left = -frame.x, top = -frame.y, right = left + frame.width, bottom = top + frame.height;
  const keepW = Math.min(KEEP, iw), keepH = Math.min(KEEP, ih);
  const stick = (v, size) => (Math.abs(v) <= magnet ? 0 : Math.abs(v - size) <= magnet ? size : Math.round(v));
  if (handle.includes('w')) left = Math.max(0, Math.min(stick(left + dx, iw), right - keepW));
  if (handle.includes('e')) right = Math.min(iw, Math.max(stick(right + dx, iw), left + keepW));
  if (handle.includes('n')) top = Math.max(0, Math.min(stick(top + dy, ih), bottom - keepH));
  if (handle.includes('s')) bottom = Math.min(ih, Math.max(stick(bottom + dy, ih), top + keepH));
  return { width: right - left, height: bottom - top, x: 0 - left, y: 0 - top };
}
/** The crop frame after the image is dragged under it, or after its size is typed: it stays inside the image. */
export function holdCrop(frame, dx, dy, iw, ih) {
  const width = Math.min(frame.width, iw), height = Math.min(frame.height, ih);
  return { width, height, x: Math.min(0, Math.max(width - iw, Math.round(frame.x + dx))), y: Math.min(0, Math.max(height - ih, Math.round(frame.y + dy))) };
}
/** The largest frame of a proportion (rw:rh) inside the image, in its middle: a crop to that proportion. */
export function ratioFrame(iw, ih, rw, rh) {
  const width = iw * rh > ih * rw ? Math.max(16, Math.round(ih * rw / rh)) : iw, height = width === iw ? Math.max(16, Math.round(iw * rh / rw)) : ih;
  return { width, height, x: 0 - Math.floor((iw - width) / 2), y: 0 - Math.floor((ih - height) / 2) };
}
// A locked proportion (Recortar and Expandir alike): once one is chosen, the frame keeps that shape while a handle is
// dragged or a size is typed, until Livre. Recortar keeps it inside the image, to the pixel. Expandir can take it
// outside, where the sides are multiples of 16, so the shape is the closest those sizes allow (within 16 px a side).
const ceil16 = n => Math.ceil(n / 16) * 16;
/**
 * The smallest frame of a proportion (rw:rh) that holds the whole image, with the image in the middle: an expansion to
 * that shape. When the image already has it, the frame is a quarter larger all around, as Expandir starts.
 */
export function aroundFrame(iw, ih, rw, rh) {
  let width = Math.max(iw, ih * rw / rh), height = width * rh / rw;
  if (width - iw < 1 && height - ih < 1) { width *= 1.25; height *= 1.25; }
  let w = Math.max(ceil16(iw), snap16(width)), h = Math.max(ceil16(ih), snap16(w * rh / rw));
  // A side raised to hold the image takes the other with it.
  w = Math.max(ceil16(iw), snap16(h * rw / rh));
  return centerFrame({ width: w, height: h, x: 0, y: 0 }, iw, ih);
}
/**
 * The frame after one of its handles is dragged with the proportion rw:rh locked. A corner holds the opposite corner and
 * follows the pointer along the side it moved most; a side moves its own edge, and the two sides next to it grow or
 * shrink evenly. `inside` (Recortar) keeps the frame inside the image; otherwise it keeps a part of the image, and once
 * it reaches outside, its sides are multiples of 16. An edge that comes within `magnet` pixels of an edge of the image
 * sticks to it.
 */
export function resizeLocked(frame, handle, dx, dy, iw, ih, rw, rh, inside = false, magnet = 0) {
  const left = -frame.x, top = -frame.y, right = left + frame.width, bottom = top + frame.height;
  const keepW = Math.min(KEEP, iw), keepH = Math.min(KEEP, ih);
  const stick = (v, size) => (Math.abs(v) <= magnet ? 0 : Math.abs(v - size) <= magnet ? size : v);
  const e = handle.includes('e'), w = handle.includes('w'), s = handle.includes('s'), n = handle.includes('n');
  // The scale the pointer asks for along each side it moves: the frame is scale × rw wide and scale × rh high.
  const alongX = e ? (stick(right + dx, iw) - left) / rw : w ? (right - stick(left + dx, iw)) / rw : null;
  const alongY = s ? (stick(bottom + dy, ih) - top) / rh : n ? (bottom - stick(top + dy, ih)) / rh : null;
  let scale = alongY === null || (alongX !== null && Math.abs(alongX - frame.width / rw) >= Math.abs(alongY - frame.height / rh)) ? alongX : alongY;
  let low = Math.max(keepW / rw, keepH / rh), high = Infinity;
  if (inside) high = Math.min((e ? iw - left : w ? right : iw) / rw, (s ? ih - top : n ? bottom : ih) / rh);
  else {
    // A held edge outside the image leaves room for the part of the image the frame keeps.
    if (e) low = Math.max(low, (keepW - left) / rw);
    if (w) low = Math.max(low, (right - iw + keepW) / rw);
    if (s) low = Math.max(low, (keepH - top) / rh);
    if (n) low = Math.max(low, (bottom - ih + keepH) / rh);
  }
  scale = Math.min(high, Math.max(low, scale));
  // Where a side of this size goes: from the held edge, or evenly around the middle of a side that does not move,
  // without leaving the image (Recortar) or the part of it the frame keeps (Expandir).
  const place = (a, b, size, movedA, movedB, image, keep) => {
    let start = movedB ? a : movedA ? b - size : Math.round((a + b - size) / 2);
    if (!movedA && !movedB) start = inside ? Math.max(0, Math.min(image - size, start)) : Math.max(keep - size, Math.min(image - keep, start));
    return start;
  };
  let width = Math.round(scale * rw), height = Math.round(scale * rh);
  let x0 = place(left, right, width, w, e, iw, keepW), y0 = place(top, bottom, height, n, s, ih, keepH);
  if (!inside && (x0 < 0 || y0 < 0 || x0 + width > iw || y0 + height > ih)) {
    width = Math.max(16, snap16(scale * rw)); height = Math.max(16, snap16(scale * rh));
    x0 = place(left, right, width, w, e, iw, keepW); y0 = place(top, bottom, height, n, s, ih, keepH);
  }
  return { width, height, x: 0 - x0, y: 0 - y0 };
}
/**
 * A typed side with the proportion rw:rh locked: the other side follows. Recortar (`inside`) keeps both within the
 * image; in Expandir a frame that reaches outside the image gets the other side in a multiple of 16.
 */
export function lockedSize(frame, side, value, iw, ih, rw, rh, inside = false) {
  let width = side === 'width' ? value : value * rw / rh, height = side === 'width' ? value * rh / rw : value;
  if (inside) {
    const fit = Math.min(1, iw / width, ih / height);
    width *= fit; height *= fit;
    return holdCrop({ ...frame, width: Math.round(width), height: Math.round(height) }, 0, 0, iw, ih);
  }
  const exact = sizeFrame(frame, Math.round(width), Math.round(height), iw, ih);
  if (frameKind(exact.width, exact.height, exact.x, exact.y, iw, ih) === 'crop') return exact;
  return sizeFrame(frame, side === 'width' ? value : Math.max(16, snap16(width)), side === 'height' ? value : Math.max(16, snap16(height)), iw, ih);
}
/** Whether a frame has a proportion (rw:rh), to the pixel it was rounded to. */
export const hasRatio = (width, height, rw, rh) => Math.abs(width * rh - height * rw) <= Math.max(rw, rh);
/** The image in the middle of the frame. */
export const centerFrame = (frame, iw, ih) => ({ width: frame.width, height: frame.height, x: Math.floor((frame.width - iw) / 2), y: Math.floor((frame.height - ih) / 2) });
/**
 * Where to draw the frame so that it and the whole image fit a stage of sw × sh with a margin around: the scale, and
 * the position on the stage of the frame's top left corner.
 */
export function frameView(frame, iw, ih, sw, sh, margin = 32) {
  const left = Math.min(0, frame.x), top = Math.min(0, frame.y), width = Math.max(frame.width, frame.x + iw) - left, height = Math.max(frame.height, frame.y + ih) - top;
  const scale = Math.max(0.01, Math.min((sw - 2 * margin) / width, (sh - 2 * margin) / height, 1));
  return { scale, x: (sw - width * scale) / 2 - left * scale, y: (sh - height * scale) / 2 - top * scale };
}
